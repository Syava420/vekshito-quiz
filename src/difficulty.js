const BASE_TERMS = /вода|h2o|поваренн|nacl|соль|хлорофилл|фотосинтез|клетк|сердц|пушкин|толстой|москва|париж|лондон|солнц|лун|меркурий|марса|байкал|эверест|росси|тихий океан|скорост.*свет|сила.*тяжест|ньютон|градус|круг|треугольник|квадрат|столиц.*росси|столиц.*франци|столиц.*италь|столиц.*япони|гагарин|1945|1941|отечественн.*1812|ленин|петров|пётр.*i|перв.*космонавт/i;

export const DIFFICULTY_CONFIG = {
  1: {
    label: 'База',
    dotClass: 'dot-level-1'
  },
  2: {
    label: 'Эрудит',
    dotClass: 'dot-level-2'
  },
  3: {
    label: 'Профи',
    dotClass: 'dot-level-3'
  }
};

export function getQuestionDifficulty(q) {
  if (q.difficulty && DIFFICULTY_CONFIG[q.difficulty]) {
    return q.difficulty;
  }
  const text = `${q.question} ${q.answer || ''} ${q.explanation || ''}`.toLowerCase();
  if (HARD_TERMS.test(text)) return 3;
  if (BASE_TERMS.test(text)) return 1;

  const num = parseInt(q.id.replace(/\D/g, ''), 10) || 0;
  if (q.id.startsWith('vk_')) {
    return num % 3 === 0 ? 3 : 2;
  }
  if (num <= 18) return 1;
  if (num <= 38) return 2;
  return 3;
}
